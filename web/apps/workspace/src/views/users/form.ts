function buildDepartmentTreeOptions(
  departments: readonly Department[],
): DepartmentTreeOption[] {
  const optionsById = new Map<string, DepartmentTreeOption>();

  for (const department of departments) {
    if (optionsById.has(department.id)) {
      throw new TypeError(`Duplicate department id: ${department.id}`);
    }

    optionsById.set(department.id, {
      children: [],
      key: department.id,
      label: department.name,
      value: department.id,
    });
  }

  const roots: DepartmentTreeOption[] = [];

  for (const department of departments) {
    const option = optionsById.get(department.id);

    if (option === undefined) {
      throw new TypeError(`Department option not found: ${department.id}`);
    }

    if (department.parent_id === null) {
      roots.push(option);
      continue;
    }

    const parent = optionsById.get(department.parent_id);

    if (parent === undefined) {
      throw new TypeError(
        `Department ${department.id} references missing parent ${department.parent_id}`,
      );
    }

    parent.children.push(option);
  }

  const visitedIds = new Set<string>();

  function visit(options: DepartmentTreeOption[]): void {
    for (const option of options) {
      if (visitedIds.has(option.value)) {
        throw new TypeError('Department hierarchy contains a cycle.');
      }

      visitedIds.add(option.value);
      visit(option.children);
    }
  }

  visit(roots);

  if (visitedIds.size !== departments.length) {
    throw new TypeError('Department hierarchy contains a cycle.');
  }

  return roots;
}

function createDateField(
  fieldName: string,
  label: string,
  dateDisplayFormat: string,
): VbenFormSchema {
  return {
    component: 'DatePicker',
    componentProps: {
      format: dateDisplayFormat,
    },
    defaultValue: null,
    fieldName,
    label,
    valueFormat: (value) => {
      if (value === null || value === undefined || value === '') {
        return null;
      }

      return dayjs(value).format('YYYY-MM-DD');
    },
  };
}

function buildBasicFormSchema(
  context: UserFormFieldContext,
  mode: 'create' | 'edit',
): VbenFormSchema[] {
  const passwordFieldName = mode === 'create' ? 'password' : 'new_password';

  return [
    {
      component: 'Input',
      fieldName: 'name',
      label: $t('page.users.fields.name'),
      rules: markRaw(
        z.string().min(1, $t('page.users.validation.nameRequired')).max(255),
      ),
    },
    ...(mode === 'edit'
      ? [
          {
            component: 'Switch' as const,
            componentProps: {
              class: 'w-auto',
            },
            defaultValue: true,
            fieldName: 'is_active',
            label: $t('page.users.fields.status'),
            rules: markRaw(z.boolean()),
          } satisfies VbenFormSchema,
        ]
      : []),
    {
      component: 'TreeSelect',
      componentProps: {
        allowClear: true,
        placeholder: $t('page.users.placeholders.department'),
        showSearch: true,
        treeData: context.departmentTreeOptions,
        treeDefaultExpandAll: true,
        treeLine: true,
        treeNodeFilterProp: 'label',
      },
      defaultValue: null,
      fieldName: 'department_id',
      label: $t('page.users.fields.department'),
    },
    {
      component: 'Input',
      ...(mode === 'create'
        ? {
            dependencies: {
              trigger(values, _actions, controller) {
                const employeeCode = values.profile?.code;
                const username = values.username;

                if (
                  employeeCode === undefined ||
                  employeeCode === '' ||
                  (username !== undefined &&
                    username !== '' &&
                    username !== context.autoGeneratedUsername.value)
                ) {
                  return;
                }

                context.autoGeneratedUsername.value = employeeCode;

                return controller.setFieldValue(
                  'username',
                  employeeCode,
                  false,
                );
              },
              triggerFields: ['profile.code'],
            },
          }
        : {}),
      fieldName: 'profile.code',
      label: $t('page.users.fields.employeeCode'),
      rules: markRaw(
        z
          .string()
          .min(1, $t('page.users.validation.employeeCodeRequired'))
          .max(36),
      ),
    },
    {
      component: 'Input',
      defaultValue: '',
      fieldName: 'username',
      formFieldProps: {
        validateOnModelUpdate: false,
      },
      label: $t('page.users.fields.username'),
      rules: markRaw(
        z
          .string()
          .min(3, $t('page.users.validation.usernameMin'))
          .max(50, $t('page.users.validation.usernameMax')),
      ),
    },
    {
      component: 'Select',
      componentProps: {
        allowClear: true,
        options: context.positions.map((position) => ({
          label: position.name,
          value: position.id,
        })),
        placeholder: $t('page.users.placeholders.position'),
      },
      defaultValue: null,
      fieldName: 'profile.position_id',
      label: $t('page.users.fields.position'),
    },
    {
      component: 'InputPassword',
      componentProps: {
        placeholder: $t('page.users.placeholders.password'),
      },
      defaultValue: '',
      fieldName: passwordFieldName,
      label: $t('page.users.fields.password'),
      rules: markRaw(
        mode === 'create'
          ? z.string().min(6, $t('page.users.validation.passwordMin')).max(255)
          : z.string().max(255),
      ),
    },
    ...(context.canEditRoles
      ? [
          {
            component: 'Select' as const,
            componentProps: {
              allowClear: true,
              mode: 'multiple' as const,
              options: context.roles.map((role) => ({
                label: role.name,
                value: role.name,
              })),
              placeholder: $t('page.users.placeholders.roles'),
            },
            defaultValue: [],
            fieldName: 'role_names',
            formItemClass: 'md:col-span-2',
            label: $t('page.users.fields.roles'),
          } satisfies VbenFormSchema,
        ]
      : []),
  ];
}

