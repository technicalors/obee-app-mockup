export function mergeUserFormValues(
  basicValues: UserFormValues,
  additionalValues: UserFormValues,
): UserFormValues {
  return {
    ...basicValues,
    ...additionalValues,
    profile: {
      ...basicValues.profile,
      ...additionalValues.profile,
    },
  };
}

export function buildUserCreatePayload(
  values: UserFormValues,
  canEditRoles: boolean,
): CreateUserPayload {
  const payload = {
    ..._.pick(values, [
      'department_id',
      'name',
      'password',
      'profile',
      'role_names',
      'username',
    ]),
    email:
      values.email === undefined || values.email === '' ? null : values.email,
  };

  if (canEditRoles) {
    return createUserPayloadSchema.parse(payload);
  }

  return createUserPayloadSchema
    .omit({ role_names: true })
    .parse(_.omit(payload, ['role_names']));
}

