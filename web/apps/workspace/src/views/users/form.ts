export function useUserFormSchema() {
  const { hasAccessByCodes } = useAccess();
  const { locale } = usePreferences();
  const roleOptionsStore = useRoleOptionsStore();
  const autoGeneratedUsername = ref<string>();
  const departments = ref<readonly Department[]>([]);
  const positions = ref<readonly Position[]>([]);
  const canEditRoles = computed(() => hasAccessByCodes(['roles.update']));
  const fieldContext = computed<UserFormFieldContext>(() => ({
    autoGeneratedUsername,
    canEditRoles: canEditRoles.value,
    dateDisplayFormat: getDatePickerDisplayFormat(locale.value),
    departmentTreeOptions: buildDepartmentTreeOptions(departments.value),
    positions: positions.value,
    roles: roleOptionsStore.roles,
  }));
  const createBasicFormSchema = computed(() =>
    buildBasicFormSchema(fieldContext.value, 'create'),
  );
  const createAdditionalFormSchema = computed(() =>
    buildAdditionalFormSchema(fieldContext.value),
  );
  const editBasicFormSchema = computed(() =>
    buildBasicFormSchema(fieldContext.value, 'edit'),
  );
  const editAdditionalFormSchema = computed(() =>
    buildAdditionalFormSchema(fieldContext.value),
  );

  async function loadOptions(): Promise<void> {
    const [nextDepartments, nextPositions] = await Promise.all([
      departmentOptionsResource.getAll(),
      positionOptionsResource.getAll(),
      canEditRoles.value ? roleOptionsStore.loadOnce() : Promise.resolve(),
    ]);

    departments.value = nextDepartments;
    positions.value = nextPositions;
  }

  return {
    canEditRoles,
    createAdditionalFormSchema,
    createBasicFormSchema,
    editAdditionalFormSchema,
    editBasicFormSchema,
    loadOptions,
  };
}
