export function buildUserPasswordResetPayload(
  values: UserFormValues,
): null | ResetUserPasswordPayload {
  if (values.new_password === '') {
    return null;
  }

  return resetUserPasswordPayloadSchema.parse({
    password: values.new_password,
    password_confirmation: values.new_password,
  });
}

