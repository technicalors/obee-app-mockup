const USER_MODAL_MINIMUM_LOADING_DURATION_MS = 500;

export async function waitForMinimumUserModalLoading(
  startedAt: number,
): Promise<void> {
  const remaining =
    USER_MODAL_MINIMUM_LOADING_DURATION_MS - (Date.now() - startedAt);

  if (remaining > 0) {
    await new Promise<void>((resolve) => setTimeout(resolve, remaining));
  }
}

