function buildOrganizationTreeOptions(
  organizations: readonly Organization[],
): OrganizationTreeOption[] {
  const optionsById = new Map<string, OrganizationTreeOption>();

  for (const organization of organizations) {
    if (optionsById.has(organization.id)) {
      throw new TypeError(`Duplicate organization id: ${organization.id}`);
    }

    optionsById.set(organization.id, {
      children: [],
      key: organization.id,
      label: organization.name,
      value: organization.id,
    });
  }

  const roots: OrganizationTreeOption[] = [];

  for (const organization of organizations) {
    const option = optionsById.get(organization.id);

    if (option === undefined) {
      throw new TypeError(`Organization option not found: ${organization.id}`);
    }

    if (organization.parent_id === null) {
      roots.push(option);
      continue;
    }

    const parent = optionsById.get(organization.parent_id);

    if (parent === undefined) {
      throw new TypeError(
        `Organization ${organization.id} references missing parent ${organization.parent_id}`,
      );
    }

    parent.children.push(option);
  }

  const visitedIds = new Set<string>();

  function visit(options: OrganizationTreeOption[]): void {
    for (const option of options) {
      if (visitedIds.has(option.value)) {
        throw new TypeError('Organization hierarchy contains a cycle.');
      }

      visitedIds.add(option.value);
      visit(option.children);
    }
  }

  visit(roots);

  if (visitedIds.size !== organizations.length) {
    throw new TypeError('Organization hierarchy contains a cycle.');
  }

  return roots;
}

function createDateField(
  fieldName: string,
  label: string,
  dateDisplayFormat: string,
): VbenFormSchema {
  return {
    component: 'DatePicker',
    componentProps: {
      format: dateDisplayFormat,
    },
    defaultValue: null,
    fieldName,
    label,
    valueFormat: (value) => {
      if (value === null || value === undefined || value === '') {
        return null;
      }

      return dayjs(value).format('YYYY-MM-DD');
    },
  };
}

function buildBasicFormSchema(
  context: UserFormFieldContext,
  mode: 'create' | 'edit',
): VbenFormSchema[] {
  const passwordFieldName = mode === 'create' ? 'password' : 'new_password';

  return [
    {
      component: 'Input',
      fieldName: 'name',
      label: $t('users.fields.name'),
      rules: markRaw(
        z.string().min(1, $t('users.validation.nameRequired')).max(255),
      ),
    },
    {
      component: 'TreeSelect',
      componentProps: {
        allowClear: true,
        placeholder: $t('users.placeholders.organization'),
        showSearch: true,
        treeData: context.organizationTreeOptions,
        treeDefaultExpandAll: true,
        treeLine: true,
        treeNodeFilterProp: 'label',
      },
      defaultValue: null,
      fieldName: 'organization_id',
      label: $t('users.fields.organization'),
    },
    {
      component: 'Input',
      ...(mode === 'create'
        ? {
            dependencies: {
              trigger(values, _actions, controller) {
                const employeeCode = values.profile?.code;
                const username = values.username;

                if (
                  employeeCode === undefined ||
                  employeeCode === '' ||
                  (username !== undefined &&
                    username !== '' &&
                    username !== context.autoGeneratedUsername.value)
                ) {
                  return;
                }

                context.autoGeneratedUsername.value = employeeCode;

                return controller.setFieldValue(
                  'username',
                  employeeCode,
                  false,
                );
              },
              triggerFields: ['profile.code'],
            },
          }
        : {}),
      fieldName: 'profile.code',
      label: $t('users.fields.employeeCode'),
      rules: markRaw(
        z.string().min(1, $t('users.validation.employeeCodeRequired')).max(36),
      ),
    },
    {
      component: 'Input',
      defaultValue: '',
      fieldName: 'username',
      formFieldProps: {
        validateOnModelUpdate: false,
      },
      label: $t('users.fields.username'),
      rules: markRaw(
        z
          .string()
          .min(3, $t('users.validation.usernameMin'))
          .max(50, $t('users.validation.usernameMax')),
      ),
    },
    {
      component: 'Select',
      componentProps: {
        allowClear: true,
        options: context.positions.map((position) => ({
          label: position.name,
          value: position.id,
        })),
        placeholder: $t('users.placeholders.position'),
      },
      defaultValue: null,
      fieldName: 'profile.position_id',
      label: $t('users.fields.position'),
    },
    {
      component: 'InputPassword',
      componentProps: {
        placeholder: $t('users.placeholders.password'),
      },
      defaultValue: '',
      fieldName: passwordFieldName,
      label: $t('users.fields.password'),
      rules: markRaw(
        mode === 'create'
          ? z.string().min(6, $t('users.validation.passwordMin')).max(255)
          : z.string().max(255),
      ),
    },
    ...(context.canEditRoles
      ? [
          {
            component: 'Select' as const,
            componentProps: {
              allowClear: true,
              mode: 'multiple' as const,
              options: context.roles.map((role) => ({
                label: role.name,
                value: role.name,
              })),
              placeholder: $t('users.placeholders.roles'),
            },
            defaultValue: [],
            fieldName: 'role_names',
            label: $t('users.fields.roles'),
          } satisfies VbenFormSchema,
        ]
      : []),
  ];
}

